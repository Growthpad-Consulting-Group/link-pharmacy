// Scans src/ for Iconify icon names (e.g. "lucide:arrow-right") and writes src/lib/icon-set.ts
// with only those icons, so they are bundled with the app instead of fetched at runtime.
// Runs automatically before `npm run dev` and `npm run build` (see package.json).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "src");
const outFile = path.join(srcDir, "lib", "icon-set.ts");

// Icon sets that have an installed @iconify-json/<prefix> package.
const PREFIXES = ["lucide", "tabler", "mdi", "ph", "logos"];

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, files);
    else if (/\.(tsx?|jsx?|mdx?)$/.test(entry.name) && full !== outFile) files.push(full);
  }
  return files;
}

const pattern = new RegExp(`\\b(${PREFIXES.join("|")}):([a-z0-9]+(?:-[a-z0-9]+)*)`, "g");
const used = new Map(); // prefix -> Set of names

for (const file of walk(srcDir)) {
  const text = fs.readFileSync(file, "utf8");
  for (const match of text.matchAll(pattern)) {
    const [, prefix, name] = match;
    if (!used.has(prefix)) used.set(prefix, new Set());
    used.get(prefix).add(name);
  }
}

const lines = [
  "/**",
  " * Icons bundled with the app so they render without a network fetch.",
  " * GENERATED by scripts/generate-icon-set.mjs. Do not edit by hand; it runs before dev and build.",
  " */",
  'import { addCollection } from "@iconify/react";',
  "",
];

for (const prefix of PREFIXES) {
  const names = [...(used.get(prefix) ?? [])].sort();
  if (names.length === 0) continue;

  const pkgFile = path.join(root, "node_modules", "@iconify-json", prefix, "icons.json");
  if (!fs.existsSync(pkgFile)) {
    throw new Error(`Missing @iconify-json/${prefix}. Run: npm install @iconify-json/${prefix}`);
  }
  const data = JSON.parse(fs.readFileSync(pkgFile, "utf8"));

  const icons = {};
  for (const name of names) {
    // Follow aliases so renamed icons still resolve.
    const alias = data.aliases?.[name];
    const base = data.icons[name] ?? (alias ? data.icons[alias.parent] : undefined);
    if (!base) {
      throw new Error(`Icon "${prefix}:${name}" was not found in @iconify-json/${prefix}`);
    }
    const { parent, ...transform } = alias ?? {};
    icons[name] = alias && !data.icons[name] ? { ...base, ...transform } : base;
  }

  const collection = { prefix, width: data.width ?? 24, height: data.height ?? 24, icons };
  lines.push(`addCollection(${JSON.stringify(collection)});`, "");
}

const next = lines.join("\n");
const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
if (current !== next) {
  fs.writeFileSync(outFile, next);
  console.log(`[icons] wrote ${path.relative(root, outFile)}`);
} else {
  console.log("[icons] icon set up to date");
}
